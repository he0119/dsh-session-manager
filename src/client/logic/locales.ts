/**
 * 界面文案：两份语言 + 命名空间。
 *
 * 形状照官方客户端插件（`dsh-client-ui-jobs`、Web 端夹具 `fixture-live-client`、官方文档
 * 「新增设置卡片」那一页的示例）：字典是扁平的 `键 → 文案`，`{name}` 是占位符；`zh` 是键集
 * 真源，`en` 按 `LocaleDictOf<NS>` 逐键核；命名空间用 `declare module` 合并进
 * `LocaleNamespaceMap`，于是注册 Slot 那里的 `locale: NS` 换来的 `t` **带键集类型**——写错
 * 键名、少一份语言，都是编译错误，不是"界面上露出一串键名"。
 *
 * 这里确实 import 了宿主客户端包，但**只 import 类型**：`verbatimModuleSyntax` 下这两条会被
 * 完全擦除，产物里一个 `require` 都不会多，客户端产物仍然只 require 平台基线模块
 * （`test/client.test.mjs` 按产物文本核这一条）。类型面绑死的代价是上游换形状时这一侧编译
 * 不过；换来的是键集校验，比"装进 profile 才现形"便宜。
 *
 * 键名点分，前缀就是它属于哪一块：`page.*` 骨架、`list.*` 会话列表、`transfer.*` 传输、
 * `migrate.*` 迁移、`manage.*` 逐条管理、`help.*` 说明、`sync.*` 同步、`dirPicker.*` 目录
 * 浏览、`backup.*` 备份与回滚；`table.*` / `cwd.*` / `tag.*` / `effect.*` / `verify.*` /
 * `error.*` 是跨页共用的那几类。取消 / 关闭 / 保存三个词**不自己写**：宿主 `common` 命名空间
 * 里有，本命名空间缺席时查找链会落到它（见 [REUSED_COMMON](#reused_common)）。
 *
 * **两份语言的键集必须完全一致**——少一个键就是一处会露出键名的界面；这条主责在编译器，
 * `test/client.test.mjs` 只再核一遍产物里的运行期事实。
 *
 * @module dsh-session-manager/client/locales
 */

